export type HazardType = 'Hurricane' | 'Earthquake' | 'Low';
export type RiskLevel = 'high' | 'moderate' | 'low';
export type InfraCategory = 'Data Center' | 'Wafer Fab' | 'Energy & Grid' | 'Logistics Hub';

export interface InfraSite {
  id: string;
  ticker: string;
  company: string;
  name: string;
  city: string;
  state: string;
  category: InfraCategory;
  lat: number;
  lng: number;
  hazard: HazardType;
  riskLevel: RiskLevel;
  unpricedImpactPct: number; // e.g. -0.6 means -0.6% unpriced risk from this site
}

export interface StockRiskProfile {
  ticker: string;
  company: string;
  weight: number; // portfolio weight % (0 - 100)
  hedgedWeight: number; // suggested rebalanced weight %
  unpricedRiskPct: number; // e.g. -1.4 means stock is overpriced by 1.4% (real value is -1.4% below market due to unpriced disaster exposure)
  primaryHazard: HazardType;
  riskLevel: RiskLevel;
  color: string;
  sites: InfraSite[];
}

export interface PortfolioPreset {
  id: string;
  label: string;
  subtitle: string;
  badge: string;
  items: { ticker: string; weight: number }[];
}


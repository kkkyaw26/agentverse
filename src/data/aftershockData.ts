export function buildPortfolioProfiles(
  rawItems: { ticker: string; weight: number }[]
): StockRiskProfile[] {
  const total = rawItems.reduce((acc, item) => acc + (Number(item.weight) || 0), 0) || 100;
  const normalized = rawItems.map((item) => ({
    ticker: item.ticker.toUpperCase().trim(),
    weight: Number(((item.weight / total) * 100).toFixed(1)),
  }));

  // Build profiles from STOCK_DATABASE or fallback deterministic profile
  const profiles: StockRiskProfile[] = normalized.map((item, idx) => {
    const known = STOCK_DATABASE[item.ticker];
    if (known) {
      return {
        ...known,
        weight: item.weight,
        hedgedWeight: item.weight,
      };
    }

    // Fallback for any custom ticker extracted from a user screenshot
    const fallbackColors = ['#E57A54', '#F4A261', '#E9C46A', '#52B788', '#A8DADC'];
    const isEven = idx % 2 === 0;
    return {
      ticker: item.ticker,
      company: `${item.ticker} Corp`,
      weight: item.weight,
      hedgedWeight: item.weight,
      unpricedRiskPct: isEven ? -0.6 : -0.3,
      primaryHazard: isEven ? 'Hurricane' : 'Earthquake',
      riskLevel: isEven ? 'moderate' : 'low',
      color: fallbackColors[idx % fallbackColors.length],
      sites: [
        {
          id: `${item.ticker.toLowerCase()}-1`,
          ticker: item.ticker,
          company: `${item.ticker} Corp`,
          name: `${item.ticker} Northern Virginia Data Center`,
          city: 'Ashburn',
          state: 'VA',
          category: 'Data Center',
          lat: 39.04 + (idx % 3) * 0.15,
          lng: -77.48 - (idx % 3) * 0.15,
          hazard: 'Hurricane',
          riskLevel: isEven ? 'moderate' : 'low',
          unpricedImpactPct: isEven ? -0.4 : -0.2,
        },
        {
          id: `${item.ticker.toLowerCase()}-2`,
          ticker: item.ticker,
          company: `${item.ticker} Corp`,
          name: `${item.ticker} Silicon Valley Hub`,
          city: 'Santa Clara',
          state: 'CA',
          category: 'Data Center',
          lat: 37.37 + (idx % 3) * 0.12,
          lng: -121.96 - (idx % 3) * 0.12,
          hazard: 'Earthquake',
          riskLevel: 'moderate',
          unpricedImpactPct: -0.2,
        },
      ],
    };
  });

  // Compute smart hedged weights: shift weight away from severe unpriced risk (<-1.0%) into resilient stocks
  const rawScores = profiles.map((p) => {
    const severity = Math.abs(p.unpricedRiskPct);
    const factor = severity >= 1.2 ? 0.62 : severity >= 0.8 ? 0.85 : 1.35;
    return p.weight * factor;
  });
  const scoreSum = rawScores.reduce((a, b) => a + b, 0) || 100;

  return profiles.map((p, i) => ({
    ...p,
    hedgedWeight: Number(((rawScores[i] / scoreSum) * 100).toFixed(1)),
  }));
}
